// Downloads the Arabic text for every verse used in renderer/js/reflections-data.js and writes
// renderer/js/quran-arabic.js, so the widget can show it without going online.
// Text: Tanzil Project (tanzil.net), via the alquran.cloud API. Run: node scripts/fetch-quran-arabic.js
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.join(__dirname, '..');
const EDITION = process.env.EDITION || 'quran-uthmani';
const BISMILLAH = /^بِسْمِ\s+[^\s]+\s+[^\s]+\s+[^\s]+\s*/;

function verseKeys(range) {
  const [surah, ayat] = range.split(':');
  const [from, to = from] = ayat.split('-').map(Number);
  return Array.from({ length: to - from + 1 }, (_, i) => `${surah}:${from + i}`);
}

(async () => {
  const context = {};
  vm.createContext(context);
  vm.runInContext(`${fs.readFileSync(path.join(ROOT, 'renderer/js/reflections-data.js'), 'utf8')}; this.REFLECTIONS = REFLECTIONS;`, context);
  const keys = [...new Set(context.REFLECTIONS.filter((r) => r.type === 'quran').flatMap((r) => verseKeys(r.verses)))];

  const arabic = {};
  const english = [];
  for (const key of keys) {
    const res = await fetch(`https://api.alquran.cloud/v1/ayah/${key}/editions/${EDITION},en.sahih`);
    if (!res.ok) throw new Error(`${key}: HTTP ${res.status}`);
    const [ar, en] = (await res.json()).data;
    let text = ar.text.trim();
    // The first verse of most surahs comes with the Bismillah in front of it.
    if (key.endsWith(':1') && !key.startsWith('1:') && BISMILLAH.test(text)) text = text.replace(BISMILLAH, '');
    arabic[key] = text;
    english.push(`${key}  ${en.text}`);
  }

  const out = `// Generated by scripts/fetch-quran-arabic.js. Do not edit by hand.
// Tanzil Quran Text (${EDITION}). Copyright (C) 2007-2021 Tanzil Project. License: Creative Commons Attribution 3.0.
// This text may be copied and used freely as long as it is not changed and this notice is kept. https://tanzil.net
const QURAN_ARABIC = ${JSON.stringify(arabic, null, 2)};
`;
  fs.writeFileSync(path.join(ROOT, 'renderer/js/quran-arabic.js'), out);
  console.log(`Wrote ${keys.length} verses.`);
  if (process.env.SHOW_ENGLISH) console.log(english.join('\n'));
})().catch((err) => {
  console.error(err.message);
  process.exit(1);
});
